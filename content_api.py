# ── Image uploads ───────────────────────────────────────────────────────────


def _slugify_name(name: str) -> str:
    stem = os.path.splitext(name or "")[0]
    normalized = unicodedata.normalize("NFKD", stem)
    ascii_only = normalized.encode("ascii", "ignore").decode("ascii").lower()
    slug = re.sub(r"[^a-z0-9]+", "-", ascii_only).strip("-")
    return slug[:60]


def _detect_extension(stream_head: bytes, declared_mime: str, filename: str):
    """(mime, extension) from the magic bytes — the declared type is a hint only.

    A browser will happily send `image/png` for an HTML file; what decides is
    what the first bytes actually are.
    """
    signatures = (
        (b"\x89PNG\r\n\x1a\n", "image/png"),
        (b"\xff\xd8\xff", "image/jpeg"),
        (b"GIF87a", "image/gif"),
        (b"GIF89a", "image/gif"),
    )
    for magic, mime in signatures:
        if stream_head.startswith(magic):
            return mime, ALLOWED_IMAGE_TYPES[mime]
    if stream_head[:4] == b"RIFF" and stream_head[8:12] == b"WEBP":
        return "image/webp", ALLOWED_IMAGE_TYPES["image/webp"]
    if stream_head[4:8] == b"ftyp" and b"avif" in stream_head[8:24]:
        return "image/avif", ALLOWED_IMAGE_TYPES["image/avif"]

    # No recognised signature: refuse rather than trust the declared type.
    guessed = declared_mime or mimetypes.guess_type(filename or "")[0] or ""
    return None, guessed


@content_bp.route("/api/admin/content/media", methods=["POST"])
@require_admin
def upload_media():
    """Store an image in the uploads volume and register it in PR_API."""
    upload = request.files.get("file")
    if upload is None or not upload.filename:
        return jsonify({"success": False, "error": "Aucun fichier reçu"}), 400

    head = upload.stream.read(32)
    upload.stream.seek(0)
    mime, extension = _detect_extension(head, upload.mimetype or "", upload.filename)
    if mime is None:
        return (
            jsonify(
                {
                    "success": False,
                    "error": "Format non reconnu — PNG, JPEG, WebP, GIF ou AVIF "
                    "uniquement (le SVG est refusé : il peut porter du script).",
                }
            ),
            415,
        )

    UPLOADS_DIR.mkdir(parents=True, exist_ok=True)
    slug = _slugify_name(upload.filename)
    stored_name = f"{secrets.token_hex(16)}{'-' + slug if slug else ''}{extension}"
    destination = UPLOADS_DIR / stored_name

    written = 0
    try:
        with open(destination, "wb") as target:
            while True:
                chunk = upload.stream.read(64 * 1024)
                if not chunk:
                    break
                written += len(chunk)
                if written > MAX_UPLOAD_BYTES:
                    raise ValueError("too large")
                target.write(chunk)
    except ValueError:
        destination.unlink(missing_ok=True)
        limit_mb = MAX_UPLOAD_BYTES // (1024 * 1024)
        return (
            jsonify({"success": False, "error": f"Image trop lourde (max {limit_mb} Mo)"}),
            413,
        )
    except OSError as e:
        destination.unlink(missing_ok=True)
        return jsonify({"success": False, "error": f"Écriture impossible : {e}"}), 500

    try:
        resp = _api(
            "POST",
            "/site-content/media",
            admin=True,
            json={
                "filename": stored_name,
                "original_name": upload.filename[:255],
                "mime_type": mime,
                "size_bytes": written,
                "alt_text": (request.form.get("alt") or "")[:400] or None,
            },
        )
    except requests.RequestException as e:
        # The registry row is what makes the file findable again; without it the
        # file is an orphan, so roll the write back rather than leak bytes.
        destination.unlink(missing_ok=True)
        return jsonify({"success": False, "error": str(e)}), 502

    if resp.status_code >= 400:
        destination.unlink(missing_ok=True)
        return _relay(resp)

    payload = resp.json().get("data", {})
    payload["url"] = f"/uploads/{stored_name}"
    payload["markdown"] = f"![{request.form.get('alt') or ''}](/uploads/{stored_name})"
    return jsonify({"success": True, "data": payload}), 201


@content_bp.route("/api/admin/content/media/<int:media_id>", methods=["DELETE"])
@require_admin
def delete_media(media_id):
    """Unregister the image, then remove the file it pointed at."""
    try:
        resp = _api("DELETE", f"/site-content/media/{media_id}", admin=True)
    except requests.RequestException as e:
        return jsonify({"success": False, "error": str(e)}), 502
    if resp.status_code >= 400:
        return _relay(resp)

    filename = (resp.json().get("data") or {}).get("filename") or ""
    if _STORED_NAME.match(filename):
        (UPLOADS_DIR / filename).unlink(missing_ok=True)
    return _relay(resp)
