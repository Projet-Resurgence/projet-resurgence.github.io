"""Editorial content API of the public site.

Reads are open proxies onto PR_API (`GET /site-content/<space>`), because the
règlement is public. Writes are gated twice: `@require_admin` checks the
administrator's own site session here, and PR_API re-checks that the service
token carries `admin.content.manage`. Neither gate is trusted alone.

Images are the one thing that does **not** live in PR_API: the bytes are
written to the `content_uploads` volume mounted on this container and served
back from `/uploads/`, and only a registry row (name, size, author) goes to
PR_API so the editor can list what exists.
"""

import mimetypes
import os
import re
import secrets
import unicodedata

import requests
from flask import Blueprint, abort, jsonify, request, send_from_directory

from auth_guard import admin_actor_headers, require_admin
from content_markdown import render as render_markdown
from pr_api_service_auth import service_auth_headers
from settings import (
    ALLOWED_IMAGE_TYPES,
    MAX_UPLOAD_BYTES,
    PR_API_URL,
    UPLOADS_DIR,
)

content_bp = Blueprint("content", __name__)

CONTENT_SPACES = ("rules", "context", "forum_rp")

# Stored names are generated by us, but the route parameter is not — a filename
# is only ever served if it matches the shape we generate.
_STORED_NAME = re.compile(r"^[0-9a-f]{32}(?:-[a-z0-9-]{1,60})?\.[a-z0-9]{2,5}$")


# ── PR_API plumbing ─────────────────────────────────────────────────────────


def _api(method: str, endpoint: str, *, admin: bool = False, **kwargs):
    headers = kwargs.pop("headers", {}) or {}
    if admin:
        headers = {**headers, **service_auth_headers(), **admin_actor_headers()}
    return requests.request(
        method, f"{PR_API_URL}{endpoint}", timeout=15, headers=headers, **kwargs
    )


def _relay(resp):
    """Forward PR_API's answer, keeping its status code."""
    try:
        payload = resp.json()
    except ValueError:
        return (
            jsonify({"success": False, "error": "Invalid response from PR_API"}),
            502,
        )
    return jsonify(payload), resp.status_code


def _proxy(method: str, endpoint: str, *, admin: bool = False, json_body=None):
    try:
        return _relay(_api(method, endpoint, admin=admin, json=json_body))
    except requests.RequestException as e:
        return jsonify({"success": False, "error": str(e)}), 502


def fetch_space(space: str, include_unpublished: bool = False) -> dict:
    """Server-side read used by the page renderer. Never raises."""
    if space not in CONTENT_SPACES:
        return {"space": space, "categories": []}
    try:
        params = {"drafts": "1"} if include_unpublished else None
        resp = _api("GET", f"/site-content/{space}", params=params)
        if resp.status_code != 200:
            return {"space": space, "categories": [], "unavailable": True}
        payload = resp.json()
        if not payload.get("success"):
            return {"space": space, "categories": [], "unavailable": True}
        return payload.get("data") or {"space": space, "categories": []}
    except (requests.RequestException, ValueError):
        # A page whose content service is down still renders its shell rather
        # than 500ing — the règlement being briefly empty beats an error page.
        return {"space": space, "categories": [], "unavailable": True}


def render_space(space: str, include_unpublished: bool = False) -> dict:
    """`fetch_space` with every body pre-rendered to HTML for the template."""
    data = fetch_space(space, include_unpublished=include_unpublished)
    for category in data.get("categories", []):
        category["summary_html"] = render_markdown(category.get("summary") or "")
        for section in category.get("sections", []):
            section["body_html"] = render_markdown(section.get("body") or "")
            section["callout_html"] = render_markdown(section.get("callout_body") or "")
    return data


# ── Public reads ────────────────────────────────────────────────────────────


@content_bp.route("/api/content/<space>")
def get_space(space):
    if space not in CONTENT_SPACES:
        return jsonify({"success": False, "error": "Unknown content space"}), 404
    return _proxy("GET", f"/site-content/{space}")


@content_bp.route("/api/content/media")
def list_media():
    return _proxy("GET", "/site-content/media")


@content_bp.route("/uploads/<path:filename>")
def serve_upload(filename):
    """Serve an uploaded image from the volume.

    `send_from_directory` already refuses to escape the directory; the name
    shape check on top means a request can only ever name a file this service
    itself created.
    """
    if not _STORED_NAME.match(filename):
        abort(404)
    if not (UPLOADS_DIR / filename).is_file():
        abort(404)
    return send_from_directory(UPLOADS_DIR, filename)


